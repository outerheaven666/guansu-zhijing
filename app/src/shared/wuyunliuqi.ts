export function yunOfStem(stem: string): { element: string; excess: '太过' | '不及' } {
  const map: Record<string, string> = {
    甲: '土', 己: '土', 乙: '金', 庚: '金', 丙: '水', 辛: '水', 丁: '木', 壬: '木', 戊: '火', 癸: '火',
  };
  const yang = ['甲', '丙', '戊', '庚', '壬'];
  return { element: map[stem], excess: yang.includes(stem) ? '太过' : '不及' };
}

