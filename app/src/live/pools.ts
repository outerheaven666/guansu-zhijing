export function drawFromPool<T>(pool: T[], seedStr: string): { item: T; no: number } {
  let h = 0;
  for (let i = 0; i < seedStr.length; i++) h = (h * 31 + seedStr.charCodeAt(i)) >>> 0;
  const idx = h % pool.length;
  return { item: pool[idx], no: idx + 1 };
}
